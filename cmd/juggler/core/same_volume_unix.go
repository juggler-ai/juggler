//go:build !windows

package core

import (
	"os"
	"syscall"
)

// sameVolume reports whether a and b are on the same device, so one can be
// renamed into the other. When either cannot say, it answers true and leaves
// the rename to find out.
func sameVolume(a, b os.FileInfo) bool {
	sa, okA := a.Sys().(*syscall.Stat_t)
	sb, okB := b.Sys().(*syscall.Stat_t)
	if !okA || !okB {
		return true
	}
	return sa.Dev == sb.Dev
}
