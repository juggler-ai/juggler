package handlers

import (
	"net/http"

	"juggler/cmd/juggler/core"
)

// HandleVersion serves GET /api/version: the server's version.
func HandleVersion(w http.ResponseWriter, r *http.Request) {
	WriteJSON(w, r, 0, map[string]any{"version": core.Version})
}
