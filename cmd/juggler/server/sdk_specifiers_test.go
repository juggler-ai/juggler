// A `juggler/*` SDK specifier resolves through five tables, one per realm or
// tool that loads it. A specifier missing from any one of them is a build that
// works everywhere except there: an extension that loads in the viewer and is
// silently dropped by the engine worker, or one the type-checker cannot follow.
const (
	sdkImportMapPrefix = "{{.BasePath}}/v{{.StaticVersion}}"
	sdkTwinsFixture    = "../../../web/js-tests/fixtures/sdk-worker-twins.json"
)

var sdkImportMapFiles = []string{
	"../../../web/index.html",
	"../../../web/engine.html",
	"../../../web/js-tests/headless-test.html",
}

const sdkJSConfig = "../../../tooling/jsconfig.json"

var importMapScript = regexp.MustCompile(`(?s)<script type="importmap"[^>]*>(.*?)</script>`)

// sdkSpecifierTables reads every registration point as specifier → module URL
// ("/sdk/ui.js"), keeping only the `juggler/*` keys.
func sdkSpecifierTables(t *testing.T) map[string]map[string]string {
	t.Helper()
	tables := map[string]map[string]string{}
	for _, file := range sdkImportMapFiles {
		src, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		m := importMapScript.FindSubmatch(src)
		if m == nil {
			t.Fatalf("%s: no <script type=\"importmap\">", file)
		}
		var importMap struct {
			Imports map[string]string `json:"imports"`
		}
		if err := json.Unmarshal(m[1], &importMap); err != nil {
			t.Fatalf("%s: import map is not JSON: %v", file, err)
		}
		table := map[string]string{}
		for k, v := range importMap.Imports {
			if strings.HasPrefix(k, "juggler/") {
				table[k] = strings.TrimPrefix(v, sdkImportMapPrefix)
			}
		}
		tables[strings.TrimPrefix(file, "../../../")] = table
	}

	src, err := os.ReadFile(sdkJSConfig)
	if err != nil {
		t.Fatal(err)
	}
	var jsconfig struct {
		CompilerOptions struct {
			Paths map[string][]string `json:"paths"`
		} `json:"compilerOptions"`
	}
	if err := json.Unmarshal(src, &jsconfig); err != nil {
		t.Fatalf("%s is not JSON: %v", sdkJSConfig, err)
	}
	table := map[string]string{}
	for k, v := range jsconfig.CompilerOptions.Paths {
		if strings.HasPrefix(k, "juggler/") {
			if len(v) != 1 {
				t.Errorf("tooling/jsconfig.json: %q maps to %d paths, want 1", k, len(v))
				continue
			}
			table[k] = strings.TrimPrefix(v[0], "../web")
		}
	}
	tables["tooling/jsconfig.json"] = table

	worker := map[string]string{}
	for k, v := range workerSDKImports {
		worker[k] = v
	}
	tables["cmd/juggler/server/worker_module.go (workerSDKImports)"] = worker
	return tables
}

// workerTwinOf is the module the engine worker loads in place of a browser
// façade that touches the DOM: `/sdk/ui.js` → `/sdk/ui-worker.js`.
func workerTwinOf(browser string) string {
	return strings.TrimSuffix(browser, ".js") + "-worker.js"
}

// TestSDKSpecifiersRegisteredEverywhere holds the five registration points of
// the `juggler/*` specifiers to one key set, and to one module per specifier —
// except that workerSDKImports may name the façade's `-worker.js` twin.
func TestSDKSpecifiersRegisteredEverywhere(t *testing.T) {
	tables := sdkSpecifierTables(t)
	names := make([]string, 0, len(tables))
	all := map[string]bool{}
	for name, table := range tables {
		names = append(names, name)
		for k := range table {
			all[k] = true
		}
	}
	sort.Strings(names)

	for _, name := range names {
		have := map[string]bool{}
		for k := range tables[name] {
			have[k] = true
		}
		if missing := missingFrom(all, have); len(missing) > 0 {
			t.Errorf("%s does not register %v, which another registration point does. "+
				"A juggler/* specifier goes in all of: %s", name, missing, strings.Join(names, ", "))
		}
	}

	browser := tables["web/index.html"]
	for _, name := range names {
		for _, spec := range sortedKeys(all) {
			got, ok := tables[name][spec]
			want := browser[spec]
			if !ok || want == "" || got == want {
				continue
			}
			if strings.HasPrefix(name, "cmd/") && got == workerTwinOf(want) {
				continue
			}
			t.Errorf("%s maps %s to %s; web/index.html maps it to %s", name, spec, got, want)
		}
	}
}

// sdkWorkerTwinsFile is the fixture unit:sdk-facade-parity reads to learn which
// specifiers have a worker twin, rendered from workerSDKImports.
type sdkWorkerTwinsFile struct {
	Comment string          `json:"_comment"`
	Twins   []sdkWorkerTwin `json:"twins"`
}

type sdkWorkerTwin struct {
	Specifier string `json:"specifier"`
	Browser   string `json:"browser"`
	Worker    string `json:"worker"`
}

func renderSDKWorkerTwins() string {
	file := sdkWorkerTwinsFile{
		Comment: "Generated by TestSDKWorkerTwinsFixture (cmd/juggler/server/sdk_specifiers_test.go) " +
			"from the -worker.js entries of workerSDKImports. UPDATE=1 rewrites it.",
		Twins: []sdkWorkerTwin{},
	}
	specs := make([]string, 0, len(workerSDKImports))
	for k := range workerSDKImports {
		specs = append(specs, k)
	}
	sort.Strings(specs)
	for _, spec := range specs {
		worker := workerSDKImports[spec]
		if !strings.HasSuffix(worker, "-worker.js") {
			continue
		}
		file.Twins = append(file.Twins, sdkWorkerTwin{
			Specifier: spec,
			Browser:   strings.TrimSuffix(worker, "-worker.js") + ".js",
			Worker:    worker,
		})
	}
	out, _ := json.MarshalIndent(file, "", "  ")
	return string(out) + "\n"
}

// TestSDKWorkerTwinsFixture keeps the twin list unit:sdk-facade-parity checks
// equal to the one the engine worker actually loads. UPDATE=1 rewrites it.
// Line endings aside: a Windows checkout gives the fixture CRLF.
func TestSDKWorkerTwinsFixture(t *testing.T) {
	got := renderSDKWorkerTwins()
	if os.Getenv("UPDATE") == "1" {
		if err := os.WriteFile(sdkTwinsFixture, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", sdkTwinsFixture)
		return
	}
	want, err := os.ReadFile(sdkTwinsFixture)
	if err != nil || strings.ReplaceAll(string(want), "\r\n", "\n") != got {
		t.Errorf("%s is stale (%v) — run UPDATE=1 make check RUN='TestSDKWorkerTwinsFixture' to rewrite it. Want:\n%s",
			strings.TrimPrefix(sdkTwinsFixture, "../../../"), errOrDiffers(err), got)
	}
}

func errOrDiffers(err error) string {
	if err != nil {
		return err.Error()
	}
	return "its contents differ from workerSDKImports"
}
