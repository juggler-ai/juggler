//go:build linux

package webviewenv

import "syscall"

// execReplace replaces this process image via execve. It only returns on
// failure; on success the new program takes over the process.
func execReplace(argv0 string, argv, env []string) error {
	return syscall.Exec(argv0, argv, env)
}
